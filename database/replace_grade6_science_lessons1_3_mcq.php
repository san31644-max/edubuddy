foreach ($sets as $order => $questions) {
    if (count($questions) !== 30) throw new RuntimeException("Lesson $order must contain exactly 30 questions.");
}

$db = db();
$db->begin_transaction();
try {
    $lessonStmt = $db->prepare("SELECT l.id, l.title_si FROM lessons l JOIN grades g ON g.id=l.grade_id JOIN subjects s ON s.id=l.subject_id WHERE g.grade_number=6 AND s.name_en='Science' AND l.medium='Sinhala' AND l.display_order=? AND l.status='active' LIMIT 1");
    $quizStmt = $db->prepare("SELECT id FROM quizzes WHERE lesson_id=? AND status='active' ORDER BY id LIMIT 1");
    $oldStmt = $db->prepare("SELECT id FROM quiz_questions WHERE quiz_id=? AND activity_type='challenge'");
    $answerDelete = $db->prepare("DELETE FROM quiz_answers WHERE question_id=?");
    $questionDelete = $db->prepare("DELETE FROM quiz_questions WHERE quiz_id=? AND activity_type='challenge'");
    $insert = $db->prepare("INSERT INTO quiz_questions (quiz_id, activity_type, question_si, option_a_si, option_b_si, option_c_si, option_d_si, correct_option, explanation_si, display_order, status) VALUES (?, 'challenge', ?, ?, ?, ?, ?, ?, ?, ?, 'active')");
    $quizUpdate = $db->prepare("UPDATE quizzes SET title_si=?, timer_minutes=30, pass_mark=50 WHERE id=?");

    foreach ($sets as $order => $questions) {
        $lessonStmt->bind_param('i', $order); $lessonStmt->execute();
        $lesson = $lessonStmt->get_result()->fetch_assoc();
        if (!$lesson) throw new RuntimeException("Grade 6 Sinhala Science lesson $order was not found.");
        $lessonId = (int)$lesson['id'];
        $quizStmt->bind_param('i', $lessonId); $quizStmt->execute();
        $quiz = $quizStmt->get_result()->fetch_assoc();
        if (!$quiz) throw new RuntimeException("Active quiz missing for lesson $order.");
        $quizId = (int)$quiz['id'];

        $oldStmt->bind_param('i', $quizId); $oldStmt->execute();
        $old = $oldStmt->get_result();
        while ($row = $old->fetch_assoc()) { $qid=(int)$row['id']; $answerDelete->bind_param('i',$qid); $answerDelete->execute(); }
        $questionDelete->bind_param('i',$quizId); $questionDelete->execute();

        foreach ($questions as $index => $q) {
            [$text,$options,$correct]=$q;
            $explanation='නිවැරදි පිළිතුර: '.strtoupper($correct);
            $position=$index+1;
            $insert->bind_param('isssssssi',$quizId,$text,$options[0],$options[1],$options[2],$options[3],$correct,$explanation,$position);
            $insert->execute();
        }
        $title='6 ශ්‍රේණිය විද්‍යාව – '.$order.' වන පාඩම – බහුවරණ ප්‍රශ්න 30ක්';
        $quizUpdate->bind_param('si',$title,$quizId); $quizUpdate->execute();
        echo "Lesson $order: 30 questions updated.\n";
    }
    $db->commit();
} catch (Throwable $e) {
    $db->rollback();
    fwrite(STDERR, $e->getMessage()."\n");
    exit(1);
}
